class LookbackTest(unittest.TestCase):
    """The 7-day window and its null-timestamp policy."""

    def test_default_lookback_is_seven_days(self):
        self.assertEqual(collector.DEFAULT_LOOKBACK_DAYS, 7.0)
        # The pinned now is 7 days after the oldest fixture record, so the
        # default window keeps the whole tree.
        cutoff = SCRIBE - 7.0 * 86400
        self.assertGreaterEqual(S1_LAST, cutoff)
        record = collector.collect(FIXTURES, collector.DEFAULT_LOOKBACK_DAYS, SCRIBE)
        self.assertEqual(record["summary"]["totalCalls"], 20)

    def test_records_outside_window_are_dropped(self):
        # now is after astra but before the later sessions; a 1-day window
        # keeps s2 (1790445989) and scribe (1790480000), drops astra.
        record = run_collect("--root", str(FIXTURES), "--lookback-days", "1",
                             "--now", "1790350000")
        engineer = agent(record, "engineer")
        self.assertEqual([m["model"] for m in engineer["models"]],
                         ["gpt-6-sol", "gpt-5.5"])
        self.assertEqual(engineer["totalCalls"], 1)
        self.assertEqual(agent(record, "scribe")["totalCalls"], 2)

    def test_null_timestamp_records_survive_any_window(self):
        # A window that would drop every known timestamp still keeps the
        # oracle rows because their timestamp is unknown.
        record = run_collect("--root", str(FIXTURES), "--lookback-days", "0",
                             "--now", str(int(S1_LAST + 1)))
        oracle = agent(record, "oracle")
        self.assertEqual(oracle["totalCalls"], 4)
        self.assertEqual(oracle["models"][0]["inputTokens"], 30210)

    def test_boundary_inclusion_at_cutoff(self):
        # cutoff == S1_LAST exactly: records AT the cutoff are included.
        record = run_collect("--root", str(FIXTURES), "--lookback-days", "1",
                             "--now", str(S1_LAST + 86400))
        engineer = agent(record, "engineer")
        astra = model(engineer, "gpt-6-astra")
        self.assertEqual(astra["calls"], 13)
        self.assertEqual(astra["lastActivityAt"], TIMES["s1_last"])

    def test_lookback_does_not_filter_profiles_out(self):
        # Even when a profile is fully outside the window it stays listed,
        # zeroed, so the UI can show "discovered but quiet".
        record = run_collect("--root", str(FIXTURES), "--lookback-days", "1",
                             "--now", "1790350000")
        ids = [a["id"] for a in record["agents"]]
        self.assertEqual(ids, ["diana", "engineer", "oracle", "scribe"])
        self.assertEqual(record["source"]["profilesDiscovered"], 4)


class FailureModeTest(unittest.TestCase):
    def test_missing_profiles_root_yields_unavailable_record(self):
        with tempfile.TemporaryDirectory() as tmp:
            record = run_collect("--root", str(Path(tmp) / "does-not-exist"))
            self.assertFalse(record["available"])
            self.assertEqual(record["source"], {"type": "local", "profilesDiscovered": 0})
            self.assertEqual(record["agents"], [])
            self.assertEqual(record["summary"], {"totalAgents": 0, "totalCalls": 0})
            self.assertEqual(record["error"]["code"], "HERMES_UNAVAILABLE")
            self.assertTrue(record["error"]["message"])

    def test_empty_profiles_root_is_available_but_quiet(self):
        with tempfile.TemporaryDirectory() as tmp:
            record = run_collect("--root", tmp)
            self.assertTrue(record["available"])
            self.assertEqual(record["agents"], [])
            self.assertEqual(record["source"]["profilesDiscovered"], 0)
            self.assertIsNone(record["error"])

    def test_corrupt_database_is_isolated_per_profile(self):
        with tempfile.TemporaryDirectory() as tmp:
            broken_dir = Path(tmp) / "broken"
            broken_dir.mkdir()
            (broken_dir / "state.db").write_bytes(b"not a sqlite database at all")
            healthy_dir = Path(tmp) / "healthy"
            healthy_dir.mkdir()
            shutil.copy(FIXTURES / "engineer" / "state.db", healthy_dir / "state.db")
            shutil.copy(FIXTURES / "engineer" / "profile.yaml", healthy_dir / "profile.yaml")

            env = dict(os.environ, TZ="America/Guayaquil")
            proc = subprocess.run(
                [sys.executable, str(SCRIPT), "--root", tmp, "--now", str(SCRIBE)],
                capture_output=True, text=True, env=env)
            self.assertEqual(proc.returncode, 0)
            record = json.loads(proc.stdout)

            self.assertTrue(record["available"])
            broken = agent(record, "broken")
            self.assertEqual(broken["models"], [])
            self.assertEqual(broken["totalCalls"], 0)
            self.assertEqual(broken["error"]["code"], "HERMES_PROFILE_UNREADABLE")
            self.assertTrue(broken["error"]["message"])
            self.assertNotIn(str(tmp), json.dumps(record["agents"]),
                             "no local paths leak into the agent entries")

            healthy = agent(record, "healthy")
            self.assertEqual(healthy["totalCalls"], 14)
            self.assertEqual(len(healthy["models"]), 3)
            self.assertIsNone(healthy["error"])

    def test_profile_without_state_db_is_reported_not_fatal(self):
        with tempfile.TemporaryDirectory() as tmp:
            (Path(tmp) / "empty-profile").mkdir()
            record = run_collect("--root", tmp)
            entry = agent(record, "empty-profile")
            self.assertEqual(entry["models"], [])
            self.assertEqual(entry["totalCalls"], 0)
            self.assertIsNotNone(entry["error"])


class UnitHelpersTest(unittest.TestCase):
    def test_non_negative_int_rejects_junk(self):
        self.assertEqual(collector.non_negative_int(None), 0)
        self.assertEqual(collector.non_negative_int("-5"), 0)
        self.assertEqual(collector.non_negative_int(-3), 0)
        self.assertEqual(collector.non_negative_int(42), 42)
        self.assertEqual(collector.non_negative_int(42.9), 42)

    def test_iso_timestamp_never_invents(self):
        self.assertIsNone(collector.iso_timestamp(None))
        self.assertIsNone(collector.iso_timestamp(0))
        self.assertIsNone(collector.iso_timestamp("junk"))
        self.assertIsNotNone(collector.iso_timestamp(1790186529.0))
        self.assertIsNone(collector.epoch_seconds(True))
        self.assertEqual(collector.epoch_seconds(1790186529.0), 1790186529.0)


