class TaskPreservedInternallyTest(unittest.TestCase):
    def test_internal_records_keep_task_verbatim(self):
        # Task is no longer in the summary contract, but must still be
        # preserved on the internal normalized event for Phase 3.
        records = collector.load_profile(FIXTURES / "engineer")
        self.assertEqual(
            {(r["sessionId"], r["task"]) for r in records if r["model"] == "gpt-6-astra"},
            {("20260923_180209_5d2a01", ""),
             ("20260923_180209_5d2a01", "approval"),
             ("20260923_180209_5d2a01", "background_review"),
             ("20260923_180209_5d2a01", "title_generation")})

    def test_task_is_not_leaked_into_the_summary_contract(self):
        text = json.dumps(full_run())
        self.assertIsNone(re.search(r'"task"\s*:', text))

    def test_internal_timestamp_is_epoch_not_iso(self):
        records = collector.load_profile(FIXTURES / "engineer")
        for record in records:
            if record["timestamp"] is not None:
                self.assertIsInstance(record["timestamp"], float)


